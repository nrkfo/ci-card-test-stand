export interface FailureDescription {
  stage: string;
  defect: string;
  action: string;
  rawCode: string;
}

export function translateFailureReason(reason: string | null | undefined): FailureDescription {
  const code = (reason || 'UNKNOWN_ERROR').trim();

  if (code === 'PAID_CHANNELS_DESCRAMBLING_FAILED') {
    return {
      stage: 'Стадия 5: Дескремблирование платных каналов (Тракт CI/CI+)',
      defect: 'Ошибка дескремблирования: CAM-модуль не раскодировал видеопоток. Сбой шины данных TS (Transport Stream) слота PCMCIA на материнской плате либо неисправен крипто-тракт.',
      action: 'Наклейте красный ярлык брака [CI_DESCRAMBLE_FAIL] и передайте ТВ на участок ремонта материнских плат для проверки пайки контактов разъёма PCMCIA.',
      rawCode: code
    };
  }

  if (code === 'NO_HARDWARE_DETECTED') {
    return {
      stage: 'Стадия 2: Аппаратный DVB / CA узел слота CI (/dev/dvb0.ca0)',
      defect: 'Аппаратный контроллер слота CI не отвечает в ядре Linux. Непропай 68-пинового разъема PCMCIA на материнской плате, обрыв шины или нет питания слота 5V/3.3V.',
      action: 'Проверьте мультиметром напряжение питания слота 5V и качество пайки ножек разъёма PCMCIA к материнской плате.',
      rawCode: code
    };
  }

  if (code === 'SLOT_PIN_SHORT_CIRCUIT') {
    return {
      stage: 'Стадия 2: Защита цепей питания слота PCMCIA',
      defect: 'Короткое замыкание или замятие пинов питания слота CI (сработала защита по току шины PCMCIA).',
      action: 'СРОЧНО ИЗВЛЕКИТЕ МОДУЛЬ! Осмотрите контакты слота CI с подсветкой: пины замкнуты между собой, риск сжечь CAM-модуль!',
      rawCode: code
    };
  }

  if (code === 'CAM_MODULE_INTERNAL_FAULT') {
    return {
      stage: 'Стадия 3: Проверка целостности CAM-модуля (Чтение CIS/ROM)',
      defect: 'Внутренний сбой микросхемы CAM-модуля: Контроллер слота ТВ активен, но чип модуля не отвечает (таймаут чтения CIS или пробой статики).',
      action: 'ВНИМАНИЕ! Проверьте тестовый CAM-модуль на эталонном ТВ. Высокая вероятность повреждения самого тестового модуля.',
      rawCode: code
    };
  }

  if (code === 'SMARTCARD_ATR_FAIL') {
    return {
      stage: 'Стадия 3: Опрос чипа смарт-карты (Протокол ISO-7816 / ATR)',
      defect: 'Смарт-карта внутри CAM-модуля не отвечает (Smartcard ATR timeout / mute). Карта не читается, окислились контакты или сгорел чип карты.',
      action: 'Извлеките смарт-карту из CAM-модуля, протрите контакты спиртом/тканью, проверьте правильность установки карты чипом к контактам.',
      rawCode: code
    };
  }

  if (code === 'NO_CAM_INSERTED_OR_NO_AUTH_LOGS') {
    return {
      stage: 'Стадия 3: Идентификация тестового CAM-модуля и чтение CIS',
      defect: 'CAM-модуль не обнаружен в разъеме. Загнуты или повреждены контакты (пины) внутри слота CI, либо модуль не вставлен до щелчка.',
      action: 'Осмотрите слот с подсветкой (все пины должны быть ровными), вставьте модуль плотно до упора и повторите тест.',
      rawCode: code
    };
  }

  if (code === 'AUTH_TIMEOUT') {
    return {
      stage: 'Стадия 4: Криптографическая аутентификация CI+ (Сеанс SAC)',
      defect: 'Таймаут рукопожатия CI+. Нестабильный электрический контакт на сигнальных линиях данных шины PCMCIA или просадка напряжения питания слота 5V.',
      action: 'Извлеките и повторно плотно вставьте CAM-модуль. При повторении — направьте плату на диагностику цепей питания слота 5V.',
      rawCode: code
    };
  }

  if (code === 'AUTH_KEY_EXCHANGE_FAILED') {
    return {
      stage: 'Стадия 4: Криптографическая аутентификация CI+ (Сертификаты безопасности)',
      defect: 'Сбой согласования сертификатов безопасности CI+ (SAC exchange error). Повреждены ключи безопасности CI+ (Device Keys) в памяти ТВ или сбой версии прошивки.',
      action: 'Передайте телевизор на повторную прошивку заводских ключей безопасности CI+ через сервисное меню.',
      rawCode: code
    };
  }

  if (code === 'SATELLITE_POOR_SIGNAL') {
    return {
      stage: 'Стадия 5: ВЧ-тюнер и спутниковый кабель LNB IN (KazSat-3)',
      defect: 'Низкий уровень или плохое качество сигнала (Уровень < 30% или Качество < 30%). Плохой контакт в разъёме LNB IN, повреждение кабеля или замятие центральной жилы.',
      action: 'Проверьте затяжку F-разъема спутникового кабеля LNB на телевизоре, осмотрите центральную жилу кабеля на предмет изгиба или окисления.',
      rawCode: code
    };
  }

  if (code === 'SATELLITE_SIGNAL_LOST') {
    return {
      stage: 'Стадия 5: ВЧ-тюнер и спутниковый тракт (KazSat-3 DVB-S2)',
      defect: 'Отсутствует сигнал спутника (DVB-S2 не залочен). Обрыв ВЧ-разъема Satellite (LNB) на плате, неисправность тюнера либо не подключен антенный кабель.',
      action: 'Проверьте физическое подключение кабеля спутниковой антенны к разъему LNB IN на ТВ и повторите тест.',
      rawCode: code
    };
  }

  if (code === 'SERIAL_NUMBER_MISMATCH' || code.includes('ПЕРЕСОРТИЦА')) {
    return {
      stage: 'Стадия 1: Двойной контроль серийного номера (Защита от пересортицы)',
      defect: 'ПЕРЕСОРТИЦА S/N: Номер на отсканированной наклейке корпуса НЕ совпадает с номером, зашитым в материнскую плату телевизора.',
      action: 'ОСТАНОВИТЬ ТЕЛЕВИЗОР! Сверить этикетку на корпусе с номером в меню ТВ, наклеить правильный штрихкод.',
      rawCode: code
    };
  }

  if (code === 'ADB_COMMUNICATION_ERROR') {
    return {
      stage: 'Стадия 1: Подключение к ТВ по ADB (TCP/IP)',
      defect: 'Нет ответа от телевизора по сети ADB. Обрыв кабеля LAN, неверный IP адрес или телевизор выключен.',
      action: 'Убедитесь, что телевизор включен и сетевой провод LAN плотно подключен к разъёму ТВ.',
      rawCode: code
    };
  }

  return {
    stage: 'Диагностика CI/CI+ тракта',
    defect: `Ошибка тестирования: ${code}`,
    action: 'Наклейте маркировку брака и передайте телевизор в ремонтную зону с описанием ошибки.',
    rawCode: code
  };
}

